// LegalText returns the site's 用户协议 ("terms") or 隐私政策 ("privacy"):
// the admin's text, or the default template, with {{site}} filled in.
func (st SiteSettings) LegalText(doc string) (string, bool) {
	var text, def string
	switch doc {
	case "terms":
		text, def = st.TermsMD, DefaultTerms
	case "privacy":
		text, def = st.PrivacyMD, DefaultPrivacy
	default:
		return "", false
	}
	if strings.TrimSpace(text) == "" {
		text = def
	}
	return strings.ReplaceAll(text, "{{site}}", st.SiteName), true
}
